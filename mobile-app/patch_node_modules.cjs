const fs = require('fs');
const path = require('path');

const targetFile = path.join(__dirname, 'node_modules', 'react-native', 'ReactCommon', 'react', 'renderer', 'core', 'graphicsConversions.h');

if (fs.existsSync(targetFile)) {
  let content = fs.readFileSync(targetFile, 'utf8');
  if (content.includes('std::format("{}%", dimension.value)')) {
    content = content.replace('std::format("{}%", dimension.value)', 'std::to_string(dimension.value) + "%"');
    fs.writeFileSync(targetFile, content, 'utf8');
    console.log('Successfully patched react-native graphicsConversions.h for C++20 compatibility on Android API < 34');
  } else {
    console.log('react-native graphicsConversions.h is already patched or does not contain std::format');
  }
} else {
  console.log('Could not find react-native graphicsConversions.h to patch.');
}

// Patch metro exports for TerminalReporter CJS resolution compatibility
const metroPaths = [
  path.join(__dirname, 'node_modules', 'metro', 'package.json'),
  path.join(__dirname, '..', 'node_modules', 'metro', 'package.json')
];

metroPaths.forEach(metroPkgPath => {
  if (fs.existsSync(metroPkgPath)) {
    try {
      const pkg = JSON.parse(fs.readFileSync(metroPkgPath, 'utf8'));
      if (pkg.exports) {
        let changed = false;
        if (!pkg.exports['./src/lib/TerminalReporter']) {
          pkg.exports['./src/lib/TerminalReporter'] = './src/lib/TerminalReporter.js';
          changed = true;
        }
        if (!pkg.exports['./src/lib/getGraphId']) {
          pkg.exports['./src/lib/getGraphId'] = './src/lib/getGraphId.js';
          changed = true;
        }
        if (!pkg.exports['./src/lib/*']) {
          pkg.exports['./src/lib/*'] = './src/lib/*.js';
          changed = true;
        }
        if (changed) {
          fs.writeFileSync(metroPkgPath, JSON.stringify(pkg, null, 2), 'utf8');
          console.log(`Successfully patched metro exports in ${metroPkgPath}`);
        }
      }
    } catch (e) {
      console.log(`Failed to patch metro exports in ${metroPkgPath}:`, e.message);
    }
  }
});
